Анализ журналов помогает восстановить последовательность событий, найти отклонения и проверить гипотезу об атаке.

## Рабочая последовательность

1. Определить систему и временной интервал.
2. Собрать релевантные источники.
3. Нормализовать время и поля.
4. Найти события, связанные с гипотезой.
5. Сопоставить их с другими источниками.
6. Зафиксировать вывод и ограничения анализа.

