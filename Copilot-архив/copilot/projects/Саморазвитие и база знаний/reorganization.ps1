function Write-Utf8File([string]$relative, [string]$content) {
    $path = Join-Path $vault $relative
    $dir = Split-Path -Parent $path
    if (-not (Test-Path -LiteralPath $dir)) { [IO.Directory]::CreateDirectory($dir) | Out-Null }
    $content = $content.TrimEnd() + "`n"
    if (Test-Path -LiteralPath $path) {
        $old = [IO.File]::ReadAllText($path, $utf8)
        if ($old -ne $content) { [IO.File]::WriteAllText($path, $content, $utf8); $script:modified++ }
    } else {
        [IO.File]::WriteAllText($path, $content, $utf8); $script:created++
    }
}

function Vault-Link([IO.FileInfo]$file) {
    $rel = $file.FullName.Substring($vault.Length + 1) -replace '\\','/' -replace '\.md$',''
    return "[[$rel|$($file.BaseName)]]"
}

function Course-IndexContent([string]$title, [string]$root, [string]$area, [string]$status, [string]$description) {
    $rootPath = Join-Path $vault $root
    $files = @(Get-ChildItem -LiteralPath $rootPath -Recurse -File -Filter '*.md' | Sort-Object FullName)
