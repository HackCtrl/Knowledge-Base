# DMZ

DMZ — выделенная сетевая зона для систем, которые должны взаимодействовать с внешней сетью. Она отделяет публичные сервисы от внутренних сегментов и позволяет задать ограниченные правила доступа.

## Практическое применение

- публикация внешних сервисов;
- запрет прямого доступа из интернета во внутреннюю сеть;
- фильтрация соединений между внешней, демилитаризованной и внутренней зонами;
