# SIEM

SIEM централизует события из разных источников, помогает искать взаимосвязи и поддерживает обнаружение и расследование инцидентов.

## Основные задачи

- сбор и хранение событий;
- нормализация данных;
- поиск и корреляция;
- формирование оповещений;
- поддержка расследования.

## Практическое применение

Источниками могут быть операционные системы, приложения, сетевые устройства и средства защиты. Качество обнаружения зависит от полноты событий, корректного времени, правил и контекста активов.

